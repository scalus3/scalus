package scalus.verify.lean

import scalus.compiler.sir.SIRType
import scalus.verify.{DataEncoding, DataLayout, DataShape, PropMacro, SirTypes}
import scalus.verify.DataEncoding.KeyOrder

import scala.collection.mutable

/** Lean types for the values of Scala types, with their `Data` encodings: what a statement or a
  * proof written in Lean names a value of a case class or an enum by.
  *
  * A case class is a `structure` of its fields, an enum an `inductive` of its constructors, a list
  * a `List` and a map a `List` of pairs. Each type has three functions, by the `Data`
  * representation the compiler gives it ([[DataLayout]]):
  *
  *   - `T.toData : T → Data`, the encoding of a value;
  *   - `T.fromData : Data → Option T`, the value a `Data` is the encoding of by its shape;
  *   - `T.wellFormed : T → Bool`, what a value has to meet besides its shape for `toData` of it to
  *     be the encoding of a value of the Scala type: the keys of a `SortedMap` ascend.
  *
  * and `T.isEncoding : Data → Bool`, that a `Data` is read as a well-formed value. A list or a map
  * is encoded by a walk of its own, a recursive definition, and not by a function passed to
  * `List.map`: Blaster gives the solver a function argument as a lambda with quantified axioms
  * ([[DataEncoding.leanPredicate]]).
  *
  * {{{
  * val types = LeanTypes.of(List(LeanTypes.typeOf[VestingDatum]))
  * types.module("LinearVesting.Generated.Types")   // the text of a Lean module
  * types.codec(LeanTypes.typeOf[VestingDatum])     // its Lean type, and how to encode a term of it
  * }}}
  *
  * What has no Lean type of its own, and is `Data` in Lean:
  *
  *   - a value of type `Data`;
  *   - a string, which is the byte string of its UTF-8, as its encoding is: that it is UTF-8 is not
  *     said, as the predicate of [[DataEncoding]] does not say it either;
  *   - a type that contains itself: `wellFormed` of it is the predicate of its encoding
  *     ([[DataEncoding.leanPredicate]]), so nothing is lost but the names of its parts;
  *   - a part whose encoding is not told ([[DataEncoding.Unknown]]), of which nothing is said.
  *     [[untyped]] lists these, with the reasons.
  */
final class LeanTypes private (
    codecs: Map[String, LeanTypes.Codec],
    /** The Lean declarations, each after those it uses. */
    val declarations: List[String],
    /** The parts whose encoding is not told, which are any `Data` in Lean, with the reasons. */
    val untyped: List[String]
) {

    /** How Lean has the values of `tp`: none for a type these were not made for. */
    def codec(tp: SIRType): Option[LeanTypes.Codec] = codecs.get(SirTypes.recursionKey(tp))

    /** The text of the Lean module `name`, as `LinearVesting.Generated.Types`: the declarations, in
      * the namespace of that name. It imports Scalus's Lean library, for PlutusCore's `Data`.
      */
    def module(name: String): String = {
        val notes =
            if untyped.isEmpty then ""
            else
                "\n\nParts whose encoding is not told, which are any `Data` here:\n" +
                    untyped.map(reason => s"- $reason").mkString("\n")
        // Not a text with a margin: the declarations have lines that begin with `|`.
        List(
          "import ScalusProofs.Run",
          "/-!\nLean types for the values of Scala types, with their `Data` encodings.\n" +
              "Generated by Scalus (`scalus.verify.lean.LeanTypes`): do not edit, generate it again." +
              s"$notes\n-/",
          s"namespace $name",
          "open PlutusCore.Integer (Integer)\nopen PlutusCore.ByteString (ByteString)\n" +
              "open PlutusCore.Data (Data)",
          declarations.mkString("\n\n"),
          s"end $name"
        ).mkString("", "\n\n", "\n")
    }
}

object LeanTypes {

    /** How Lean has the values of a Scala type. */
    final case class Codec(
        /** A name for the type that an identifier may have: that of the Lean type, for a case class
          * or an enum.
          */
        id: String,
        /** The Lean type, as a term: `Integer`, `VestingDatum`, `(List TxOut)`. */
        leanType: String,
        /** The Lean term of the `Data` of a term of the type. */
        toData: String => String,
        /** The Lean term of the value a `Data` term encodes, an `Option` of the type. */
        fromData: String => String,
        /** The Lean term, a `Bool`, of what a term of the type has to meet for its `Data` to be the
          * encoding of a value: none for a type every value of which does.
          */
        wellFormed: Option[String => String],
        /** Whether the well-formed values of the Lean type are exactly the values of the Scala
          * type: not so for a string, or a part whose encoding is not told.
          */
        exact: Boolean
    )

    /** The SIR type of `A`, as the compiler has it. */
    inline def typeOf[A]: SIRType = ${ PropMacro.sirType[A] }

    /** The Lean types of `types` and of every type their values are made of, each once. */
    def of(types: Iterable[SIRType]): LeanTypes = of(types, Map.empty)

    /** [[of]], where the types `bound` names, by the full names of their Scala declarations, are
      * Lean types that exist already, each with the codec given for it: nothing is declared for
      * one, nor for what only it is made of. So a script context can be that of a Lean library of
      * the ledger, with that library's validity predicate as what a value has to meet:
      *
      * {{{
      * LeanTypes.of(types, Map(
      *   "scalus.cardano.onchain.plutus.v3.ScriptContext" -> LeanTypes.Codec(
      *     "ScriptContext", "CardanoLedgerApi.V3.Contexts.ScriptContext",
      *     x => s"(IsData.toData $x)", d => s"(IsData.fromData $d)",
      *     Some(x => s"(validScriptContext $x)"), exact = false)))
      * }}}
      *
      * That the Lean type's `Data` is the one Scalus's values have is the caller's to check: here
      * it is taken as said.
      */
    def of(types: Iterable[SIRType], bound: Map[String, Codec]): LeanTypes = {
        val builder = new Builder(bound)
        types.foreach(builder.codec)
        builder.result
    }

    /** The Lean definitions every module of types has: how the types without a declaration of their
      * own are read from `Data`.
      */
    private val prelude: List[String] = List(
      "def scalusInteger? : Data → Option Integer\n  | Data.I i => some i\n  | _ => none",
      "def scalusBytes? : Data → Option ByteString\n  | Data.B b => some b\n  | _ => none",
      "def scalusBoolData (b : Bool) : Data := Data.Constr (if b then 1 else 0) []",
      "def scalusBool? : Data → Option Bool\n" +
          "  | Data.Constr t [] => if t == 0 then some false else if t == 1 then some true else none\n" +
          "  | _ => none"
    )

    /** Names a declaration here cannot have: those of the types the declarations are written with.
      */
    private val reserved = Set(
      "Data",
      "Integer",
      "ByteString",
      "Bool",
      "String",
      "List",
      "Option",
      "Nat",
      "Int",
      "Unit",
      "Prod",
      "Type",
      "Prop",
      "Sort"
    )

    /** Words a Lean name cannot be without `«»`. */
    private val keywords = Set(
      "abbrev",
      "at",
      "attribute",
      "axiom",
      "by",
      "calc",
      "catch",
      "class",
      "def",
      "deriving",
      "do",
      "else",
      "end",
      "example",
      "exists",
      "extends",
      "finally",
      "for",
      "forall",
      "from",
      "fun",
      "have",
      "if",
      "import",
      "in",
      "inductive",
      "infix",
      "instance",
      "let",
      "local",
      "macro",
      "match",
      "mutual",
      "namespace",
      "nomatch",
      "nofun",
      "notation",
      "open",
      "opaque",
      "partial",
      "prefix",
      "private",
      "protected",
      "return",
      "scoped",
      "section",
      "show",
      "structure",
      "suffices",
      "syntax",
      "then",
      "theorem",
      "try",
      "universe",
      "unless",
      "unsafe",
      "using",
      "variable",
      "where",
      "with"
    )

    /** `name` as the Lean name of a field or a constructor. */
    private[lean] def leanName(name: String): String = {
        val plain = name.nonEmpty && !name.head.isDigit &&
            name.forall(c => c < 128 && (c.isLetterOrDigit || c == '_' || c == '\''))
        if plain && !keywords(name) then name else s"«$name»"
    }

    private val integer = Codec(
      "Integer",
      "Integer",
      x => s"(Data.I $x)",
      d => s"(scalusInteger? $d)",
      None,
      exact = true
    )

    private def bytes(exact: Boolean) = Codec(
      "ByteString",
      "ByteString",
      x => s"(Data.B $x)",
      d => s"(scalusBytes? $d)",
      None,
      exact
    )

    private val bool = Codec(
      "Bool",
      "Bool",
      x => s"(scalusBoolData $x)",
      d => s"(scalusBool? $d)",
      None,
      exact = true
    )

    private def anyData(exact: Boolean) =
        Codec("Data", "Data", x => x, d => s"(some $d)", None, exact)

    /** `match` of an `Option` term: `found` of the name bound to its value, or none. */
    private def bind(option: String, name: String, found: String): String =
        s"(match $option with | some $name => $found | none => none)"

    /** The Lean term that reads the `Data` terms `d0`, `d1`, … by `codecs`, in turn, and is `made`
      * of the values `v0`, `v1`, … read.
      */
    private def reads(codecs: List[Codec], made: List[String] => String): String = {
        val values = codecs.indices.map(i => s"v$i").toList
        codecs.zipWithIndex.foldRight(s"some ${made(values)}") { case ((codec, i), rest) =>
            bind(codec.fromData(s"d$i"), s"v$i", rest)
        }
    }

    /** The Lean term that reads the fields `fs` of a constructor by `codecs`. */
    private def readsFields(codecs: List[Codec], made: List[String] => String): String = {
        val pattern = codecs.indices.map(i => s"d$i").mkString("[", ", ", "]")
        s"(match fs with | $pattern => ${reads(codecs, made)} | _ => none)"
    }

    private def application(function: String, arguments: List[String]): String =
        if arguments.isEmpty then function else s"($function ${arguments.mkString(" ")})"

    private def conjunction(tests: List[String]): String =
        if tests.isEmpty then "true" else tests.mkString(" && ")

    private final class Builder(bound: Map[String, Codec]) {
        private val codecs = mutable.LinkedHashMap.empty[String, Codec]
        private val declarations = mutable.ListBuffer.empty[String]
        private val untyped = mutable.ListBuffer.empty[String]

        /** The key of the type each name declared here is of. */
        private val declared = mutable.Map.empty[String, String]

        /** The encodings of the types that contain themselves, whose predicates are defined. */
        private val recursive = mutable.ListBuffer.empty[DataEncoding]

        def result: LeanTypes = {
            val predicates =
                if recursive.isEmpty then Nil
                else DataEncoding.leanDefinitions :: DataEncoding.leanRecursions(recursive.toList)
            new LeanTypes(
              codecs.toMap,
              prelude ++ predicates ++ declarations.toList,
              untyped.toList.distinct
            )
        }

        /** The keys of the types whose codecs are being derived. */
        private val deriving = mutable.Set.empty[String]

        def codec(tp: SIRType): Codec = {
            val key = SirTypes.recursionKey(tp)
            codecs.get(key) match
                case Some(known) => known
                // A type asked for again while it is derived contains itself, though its layout
                // is no `Recursive` one: where `DataLayout` cut the layout off at its size. Its
                // values are any `Data` here, as those of a part whose encoding is not told.
                case None if deriving(key) =>
                    untyped += s"${tp.show} contains itself, and its layout was cut off"
                    anyData(exact = false)
                case None =>
                    deriving += key
                    val derived =
                        try
                            bound
                                .get(SirTypes.declarationName(SirTypes.unwrap(tp)))
                                .getOrElse(derive(tp, key))
                        finally deriving -= key
                    codecs(key) = derived
                    derived
        }

        private def derive(tp: SIRType, key: String): Codec = {
            DataLayout.of(tp) match {
                // A type that contains itself has no Lean type of its own: its values are the
                // `Data` its encoding's predicate holds of.
                case layout: DataLayout.Recursive =>
                    val encoding = layout.encoding
                    recursive += encoding
                    val holds = encoding.leanPredicate
                    Codec(
                      holds,
                      "Data",
                      x => x,
                      d => s"(if $holds $d then some $d else none)",
                      Some(x => s"($holds $x)"),
                      encoding.exact
                    )
                case _ =>
                    DataLayout.shape(tp) match
                        case DataShape.Plain(DataEncoding.Integer) => integer
                        case DataShape.Plain(DataEncoding.Bytes)   => bytes(exact = true)
                        case DataShape.Plain(DataEncoding.Text)    => bytes(exact = false)
                        case DataShape.Plain(DataEncoding.Bool)    => bool
                        case DataShape.Plain(DataEncoding.AnyData) => anyData(exact = true)
                        case DataShape.Plain(DataEncoding.Unknown(reason)) =>
                            untyped += reason
                            anyData(exact = false)
                        case DataShape.Plain(other) =>
                            untyped += s"${tp.show}: $other"
                            anyData(exact = false)
                        case DataShape.Record(fields)        => record(tp, key, fields)
                        case DataShape.Choice(constructors)  => choice(tp, key, constructors)
                        case DataShape.Wrapper(field, inner) => wrapper(tp, key, field, inner)
                        case DataShape.Collection(items)     => collection(codec(items))
                        case DataShape.Mapping(keys, values, order) =>
                            mapping(codec(keys), codec(values), order)
            }
        }

        /** A name for `tp` that says its type arguments: `Option_Integer`. */
        private def described(tp: SIRType): String = SirTypes.unwrap(tp) match
            case SIRType.Integer    => "Integer"
            case SIRType.ByteString => "ByteString"
            case SIRType.String     => "String"
            case SIRType.Boolean    => "Bool"
            case other =>
                val declaration = SirTypes.declarationName(other)
                if declaration.isEmpty then "T"
                else
                    (DataLayout.leanSimpleName(declaration) ::
                        SirTypes.typeArgumentsOf(other).map(described)).mkString("_")

        /** The name of the Lean type of `tp`, of the key `key`: its declaration's and its type
          * arguments', and, where another type has that name already, or Lean has it, the hash of
          * its key too.
          */
        private def declare(tp: SIRType, key: String): String = {
            val plain = described(tp)
            val name =
                if reserved(plain) || declared.get(plain).exists(_ != key) then
                    s"${plain}_${DataEncoding.digest(key)}"
                else plain
            declared(name) = key
            name
        }

        private def named(id: String, hasChecks: Boolean, exact: Boolean): Codec = {
            declarations += s"def $id.isEncoding (d : Data) : Bool :=\n" +
                s"  match $id.fromData d with | some x => $id.wellFormed x | none => false"
            Codec(
              id,
              id,
              x => s"($id.toData $x)",
              d => s"($id.fromData $d)",
              Option.when(hasChecks)(x => s"($id.wellFormed $x)"),
              exact
            )
        }

        private def record(tp: SIRType, key: String, fields: List[(String, SIRType)]): Codec = {
            val parts = fields.map((name, field) => leanName(name) -> codec(field))
            val id = declare(tp, key)
            val codecs = parts.map(_._2)
            val structure =
                if parts.isEmpty then s"structure $id\n  deriving DecidableEq, Repr"
                else
                    val members = parts.map((name, part) => s"  $name : ${part.leanType}")
                    s"structure $id where\n${members.mkString("\n")}\n  deriving DecidableEq, Repr"
            val encoded = parts.map((name, part) => part.toData(s"x.$name"))
            val toData =
                if parts.isEmpty then s"def $id.toData : $id → Data\n  | _ => Data.Constr 0 []"
                else
                    s"def $id.toData (x : $id) : Data :=\n" +
                        s"  Data.Constr 0 [${encoded.mkString(", ")}]"
            val read = readsFields(codecs, values => application(s"$id.mk", values))
            val fromData = s"def $id.fromData : Data → Option $id\n" +
                s"  | Data.Constr t fs => if t == 0 then $read else none\n" +
                "  | _ => none"
            val checks = parts.flatMap((name, part) => part.wellFormed.map(_(s"x.$name")))
            val wellFormed =
                if checks.isEmpty then s"def $id.wellFormed : $id → Bool\n  | _ => true"
                else s"def $id.wellFormed (x : $id) : Bool :=\n  ${conjunction(checks)}"
            declarations ++= List(structure, toData, fromData, wellFormed)
            named(id, checks.nonEmpty, codecs.forall(_.exact))
        }

        private def choice(
            tp: SIRType,
            key: String,
            constructors: List[(String, List[(String, SIRType)])]
        ): Codec = {
            val read = constructors.map { (name, fields) =>
                DataLayout.leanSimpleName(name) ->
                    fields.map((field, of) => leanName(field) -> codec(of))
            }
            val id = declare(tp, key)
            // The functions of a type are in its namespace, where a constructor's name is seen
            // before a type's. A constructor named as the type, as `OutputDatum.OutputDatum`, as
            // the type of a field, or as a type the declarations are written with, would be taken
            // for that type there: it has a `'` after its name.
            val taken = reserved + id ++ read.flatMap(_._2.map(_._2.id))
            val parts = read.map { (name, fields) =>
                leanName(if taken(name) then s"$name'" else name) -> fields
            }
            val cases = parts.map { (name, fields) =>
                val members = fields.map((field, part) => s" ($field : ${part.leanType})")
                s"  | $name${members.mkString}"
            }
            val inductive =
                s"inductive $id where\n${cases.mkString("\n")}\n  deriving DecidableEq, Repr"
            def binders(fields: List[(String, Codec)]) = fields.indices.map(i => s"a$i").toList
            val encodes = parts.zipWithIndex.map { case ((name, fields), tag) =>
                val encoded = fields.zip(binders(fields)).map { case ((_, part), a) =>
                    part.toData(a)
                }
                val pattern = (s".$name" :: binders(fields)).mkString(" ")
                s"  | $pattern => Data.Constr $tag [${encoded.mkString(", ")}]"
            }
            val toData = s"def $id.toData : $id → Data\n${encodes.mkString("\n")}"
            val reads = parts.zipWithIndex.foldRight("none") { case (((name, fields), tag), rest) =>
                val read =
                    readsFields(fields.map(_._2), values => application(s"$id.$name", values))
                s"if t == $tag then $read\n    else $rest"
            }
            val fromData = s"def $id.fromData : Data → Option $id\n" +
                s"  | Data.Constr t fs =>\n    $reads\n" +
                "  | _ => none"
            val checked = parts.map { (name, fields) =>
                val tests = fields.zip(binders(fields)).map { case ((_, part), a) =>
                    part.wellFormed.map(_(a)).map(a -> _)
                }
                val pattern = (s".$name" :: tests.map(_.fold("_")(_._1))).mkString(" ")
                (s"  | $pattern => ${conjunction(tests.flatten.map(_._2))}", tests.flatten.nonEmpty)
            }
            val hasChecks = checked.exists(_._2)
            val wellFormed =
                if hasChecks then
                    s"def $id.wellFormed : $id → Bool\n${checked.map(_._1).mkString("\n")}"
                else s"def $id.wellFormed : $id → Bool\n  | _ => true"
            declarations ++= List(inductive, toData, fromData, wellFormed)
            named(id, hasChecks, parts.forall(_._2.forall(_._2.exact)))
        }

        private def wrapper(tp: SIRType, key: String, field: String, of: SIRType): Codec = {
            val inner = codec(of)
            val id = declare(tp, key)
            val name = leanName(field)
            val structure =
                s"structure $id where\n  $name : ${inner.leanType}\n  deriving DecidableEq, Repr"
            val toData = s"def $id.toData (x : $id) : Data :=\n  ${inner.toData(s"x.$name")}"
            val fromData = s"def $id.fromData (d : Data) : Option $id :=\n" +
                s"  ${bind(inner.fromData("d"), "v", s"some ($id.mk v)")}"
            val check = inner.wellFormed.map(_(s"x.$name"))
            val wellFormed = check match
                case Some(test) => s"def $id.wellFormed (x : $id) : Bool :=\n  $test"
                case None       => s"def $id.wellFormed : $id → Bool\n  | _ => true"
            declarations ++= List(structure, toData, fromData, wellFormed)
            named(id, check.nonEmpty, inner.exact)
        }

        /** Declares the walk `name` where it is not declared yet. */
        private def walk(name: String, text: => String): Unit =
            if !declared.contains(name) then
                declared(name) = name
                declarations += text

        private def collection(items: Codec): Codec = {
            val id = s"List_${items.id}"
            val list = s"List ${items.leanType}"
            walk(
              s"$id.toData",
              s"def $id.toData : $list → List Data\n" +
                  "  | [] => []\n" +
                  s"  | x :: xs => ${items.toData("x")} :: $id.toData xs"
            )
            val rest = bind(s"$id.fromData ds", "xs", "some (x :: xs)")
            walk(
              s"$id.fromData",
              s"def $id.fromData : List Data → Option ($list)\n" +
                  "  | [] => some []\n" +
                  s"  | d :: ds => ${bind(items.fromData("d"), "x", rest)}"
            )
            items.wellFormed.foreach { check =>
                walk(
                  s"$id.wellFormed",
                  s"def $id.wellFormed : $list → Bool\n" +
                      "  | [] => true\n" +
                      s"  | x :: xs => ${check("x")} && $id.wellFormed xs"
                )
            }
            Codec(
              id,
              s"($list)",
              x => s"(Data.List ($id.toData $x))",
              d => s"(match $d with | Data.List ds => $id.fromData ds | _ => none)",
              items.wellFormed.map(_ => x => s"($id.wellFormed $x)"),
              items.exact
            )
        }

        private def mapping(keys: Codec, values: Codec, order: KeyOrder): Codec = {
            val sorted = order == KeyOrder.Bytes || order == KeyOrder.Integers
            val id = s"${if sorted then "SortedMap" else "Map"}_${keys.id}_${values.id}"
            val list = s"List (${keys.leanType} × ${values.leanType})"
            walk(
              s"$id.toData",
              s"def $id.toData : $list → List (Data × Data)\n" +
                  "  | [] => []\n" +
                  s"  | (k, v) :: rest => (${keys.toData("k")}, ${values.toData("v")}) :: $id.toData rest"
            )
            val rest = bind(s"$id.fromData rest", "entries", "some ((k, v) :: entries)")
            val entry = bind(keys.fromData("dk"), "k", bind(values.fromData("dv"), "v", rest))
            walk(
              s"$id.fromData",
              s"def $id.fromData : List (Data × Data) → Option ($list)\n" +
                  "  | [] => some []\n" +
                  s"  | (dk, dv) :: rest => $entry"
            )
            val entryChecks = List(keys.wellFormed.map(_("k")), values.wellFormed.map(_("v")))
            if entryChecks.flatten.nonEmpty then
                val pattern = entryChecks
                    .zip(List("k", "v"))
                    .map((check, name) => if check.isEmpty then "_" else name)
                walk(
                  s"$id.entriesWellFormed",
                  s"def $id.entriesWellFormed : $list → Bool\n" +
                      "  | [] => true\n" +
                      s"  | (${pattern.mkString(", ")}) :: rest => " +
                      s"${conjunction(entryChecks.flatten)} && $id.entriesWellFormed rest"
                )
            // The keys ascend: each is checked against the previous one, an argument, on the tail
            // of its entry. Recursion on a sublist bound by an as-pattern,
            // `(a, _) :: tail@((b, _) :: _) => … tail`, Lean-blaster does not return on from
            // `1fe209e` on (Lean-blaster#463).
            if sorted then
                walk(
                  s"$id.ascendingFrom",
                  s"def $id.ascendingFrom (previous : ${keys.leanType}) : $list → Bool\n" +
                      "  | [] => true\n" +
                      s"  | (k, _) :: rest => decide (previous < k) && $id.ascendingFrom k rest"
                )
                walk(
                  s"$id.ascending",
                  s"def $id.ascending : $list → Bool\n" +
                      "  | [] => true\n" +
                      s"  | (k, _) :: rest => $id.ascendingFrom k rest"
                )
            val checks: List[String => String] =
                Option
                    .when(entryChecks.flatten.nonEmpty)((x: String) => s"$id.entriesWellFormed $x")
                    .toList ++
                    Option.when(sorted)((x: String) => s"$id.ascending $x").toList
            Codec(
              id,
              s"($list)",
              x => s"(Data.Map ($id.toData $x))",
              d => s"(match $d with | Data.Map ps => $id.fromData ps | _ => none)",
              Option.when(checks.nonEmpty)(x => s"(${conjunction(checks.map(_(x)))})"),
              keys.exact && values.exact && order != KeyOrder.Unchecked
            )
        }
    }
