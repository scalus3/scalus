package scalus.uplc.jit

import scalus.uplc.{Constant, NamedDeBruijn}
import scalus.uplc.eval.*

import scala.quoted.*

/** What the code generators need: references in generated code, and the constant pool.
  *
  * The `Expr` fields are references, in generated code, to a parameter of the compiled function
  * `(logger, budget, params) => ...`. They are not values: the generator runs at JIT-compile time
  * and only splices these references into the code it generates.
  *
  * Passed as a `given`, so a generator that adds a field does not change the signature of every
  * `genCode`.
  *
  * @param logger
  *   the `Logger` of the evaluation, for `trace`
  * @param budget
  *   the `BudgetSpender` of the evaluation
  * @param params
  *   the `MachineParams` of the evaluation: the step costs and the builtin cost model
  * @param consts
  *   the hoisted constants of the script (see [[ConstantPool]]), a parameter of the function the
  *   generated code is wrapped in
  * @param pool
  *   the constant pool of the script, a JIT-compile-time value: which constant sits in which slot
  *   of `consts`
  */
final case class GenCtx(
    logger: Expr[Logger],
    budget: Expr[BudgetSpender],
    params: Expr[MachineParams],
    consts: Expr[Array[UplcValue]],
    pool: ConstantPool
) {

    /** Generates the code that gives the value of `(con c)`: `consts(3)`, a read of the constant
      * array ([[ConstantPool]]).
      */
    def constant(c: Constant)(using Quotes): Expr[UplcValue] =
        pool.read(c, consts)
}

object GenCtx {

    /** Generates the spend of one machine step of `kind`: one static call of [[JitBudget]].
      *
      * For `spendStep(StepKind.Var)` it generates:
      * {{{
      * JitBudget.spendVar(budget, params)
      * }}}
      * which spends `params.machineCosts.varCost` in category `Step(StepKind.Var)`, the step
      * `Cek.scala` `computeCek` spends for a `Var` term. The cost is read from `params` at
      * evaluation time, so one compiled script runs with any machine parameters.
      *
      * compile time: the match on `kind` chooses the method; only its call is generated. One call
      * per site keeps the generated methods small: an inlined `spendBudget` with its `Step`
      * allocation and cost lookup was about 64 % of the generated bytecode.
      */
    def spendStep(kind: StepKind)(using ctx: GenCtx, q: Quotes): Expr[Unit] = {
        val b = ctx.budget
        val p = ctx.params
        kind match
            case StepKind.Const   => '{ JitBudget.spendConst($b, $p) }
            case StepKind.Var     => '{ JitBudget.spendVar($b, $p) }
            case StepKind.LamAbs  => '{ JitBudget.spendLamAbs($b, $p) }
            case StepKind.Apply   => '{ JitBudget.spendApply($b, $p) }
            case StepKind.Delay   => '{ JitBudget.spendDelay($b, $p) }
            case StepKind.Force   => '{ JitBudget.spendForce($b, $p) }
            case StepKind.Builtin => '{ JitBudget.spendBuiltin($b, $p) }
            case StepKind.Constr  => '{ JitBudget.spendConstr($b, $p) }
            case StepKind.Case    => '{ JitBudget.spendCase($b, $p) }
    }

    /** Generates the spends of a let-binding `[(lam x body) arg]`, the Apply and the LamAbs step:
      * `JitBudget.spendLet(budget, params)`.
      */
    def spendLet(using ctx: GenCtx, q: Quotes): Expr[Unit] =
        '{ JitBudget.spendLet(${ ctx.budget }, ${ ctx.params }) }

    /** Generates the code for a variable that no lambda binds:
      * `throw OpenTermEvaluatedMachineError(NamedDeBruijn("x"), Nil)`. The CEK machine fails on it
      * when it evaluates it, not before, with that error, so the JIT compiles it and fails at the
      * same point.
      */
    def freeVariable(name: String)(using Quotes): Expr[UplcValue] =
        '{ throw new OpenTermEvaluatedMachineError(NamedDeBruijn(${ Expr(name) }), Nil) }
}
