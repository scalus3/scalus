#!/usr/bin/env bash
# Writes coverage-exclude.sbt (git-ignored) at the repo root: the main source files that scoverage
# must not instrument. See docs/internal/test-refactor/coverage.md and finding F-9.
#
# Excluded: files with @Compile code, and files that call Scalus plugin intrinsics whose arguments
# must stay literals (compiledModules, compile { }, PlutusV*.compile, ...). A coverage probe inside
# such code fails the build: "Literals of type Int can't be used in Scalus scripts".
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

files=$( {
    git grep -l -E '^\s*@Compile' -- '*/src/main/*.scala'
    git grep -l -E 'compiledModules\(|PlutusV[1234]\.compile|Compiler\.compile|\bcompile\s*\{|compileWithOptions|compileInline' -- '*/src/main/*.scala'
} | sort -u)

# scoverage matches the path without the .scala suffix.
pattern=$(printf '%s\n' "$files" | perl -pe 's|.*/scala/||; s|\.scala$||; s/\./\\\\./g' | paste -sd'|' -)

printf '// Generated by docs/internal/test-refactor/scripts/coverage-exclude.sh. Do not edit.\n' > coverage-exclude.sbt
printf 'ThisBuild / coverageExcludedFiles := ".*/(%s)"\n' "$pattern" >> coverage-exclude.sbt
echo "coverage-exclude.sbt: $(printf '%s\n' "$files" | wc -l | tr -d ' ') files excluded"
