/** Costs for the builtins that the van Rossem (PV11) semantics variants D and E add, taken from the
  * vendored Plutus reference models `builtinCostModelD.json` and `builtinCostModelE.json`.
  *
  * A cost model set by governance before van Rossem has no entries for these builtins, so reading
  * them yields the `300_000_000` placeholder that `PlutusParams.fromSeq` fills in for absent
  * parameters, which would make the new builtins absurdly expensive.
  * [[MachineParams.fromCostModels]] therefore substitutes these values, and only these, leaving
  * every builtin that the supplied model does cover on its governance-set cost.
  *
  * The values are literals rather than a parse of the JSON resources at runtime because
  * `BuiltinCostModel.fromJsonString` is a upickle reader, and `Data.fromJson` aside it was the last
  * thing keeping upickle, ujson and upack in the published `scalus.js` bundle. Variants D and E
  * carry identical values for all fourteen builtins, so one set covers both.
  *
  * Generated by `scripts/gen-vanrossem-costs.py`; do not hand-edit, and re-run that script (then
  * `scalafmtAll`) when the vendored resources change. `VanRossemNewBuiltinCostsTest` compares every
  * field with `BuiltinCostModel.vanRossemReferenceD` and `...E`, so a resource change fails the
  * build rather than silently mispricing a builtin. See `docs/internal/JS_BUNDLE_SIZE.md`.
